// Run from any directory after editing backend/data/modules.json.
// Keep a generated TS bundle so frontend-only Docker builds stay self-contained.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const modules = JSON.parse(fs.readFileSync(path.join(root, 'backend/data/modules.json'), 'utf8'));
const target = path.join(root, 'frontend/src/app/learn/modules.ts');
const types = fs.readFileSync(path.join(root, 'frontend/src/app/learn/curriculum-types.ts'), 'utf8');
const output = '// Generated by frontend/scripts/sync-curriculum.cjs. Edit backend/data/modules.json.\n'
  + types + '\nexport const modules: Module[] = ' + JSON.stringify(modules, null, 2) + ';\n\n'
  + 'export function getModule(id: number): Module | undefined {\n  return modules.find((module) => module.id === id);\n}\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node frontend/scripts/sync-curriculum.cjs');
} else fs.writeFileSync(target, output);
